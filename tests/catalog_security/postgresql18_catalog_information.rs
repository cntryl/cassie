#[test]
fn should_report_created_object_catalog_identity_metadata() {
    // Arrange
    let fixture = sql_fixture(
        "issue-817-created-object-catalog-identity",
        &[
            "CREATE SCHEMA issue_817_catalog_probe",
            "CREATE TABLE issue_817_catalog_probe.items (\
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
                amount NUMERIC(7, 2) NOT NULL DEFAULT 1.25, \
                CONSTRAINT issue_817_amount_positive CHECK (amount > 0))",
            "CREATE INDEX issue_817_amount_idx ON issue_817_catalog_probe.items(amount)",
        ],
    );
    fixture.cassie.startup().expect("startup");

    // Act
    let relations = fixture
        .execute(
            "SELECT c.relname, c.relkind::text, c.relpersistence::text, \
                    pg_catalog.pg_get_userbyid(c.relowner) = current_user \
             FROM pg_catalog.pg_class AS c \
             JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace \
             WHERE n.nspname = 'issue_817_catalog_probe' \
               AND c.relname IN ('items', 'items_amount_idx', 'items_id_seq', 'items_pkey') \
             ORDER BY c.relname",
        )
        .expect("read relation identities and ownership");
    let attributes = fixture
        .execute(
            "SELECT attname, attnum, atttypid, atttypmod, attnotnull, attidentity::text \
             FROM pg_catalog.pg_attribute \
             WHERE attrelid = 'issue_817_catalog_probe.items'::regclass \
               AND attnum > 0 \
             ORDER BY attnum",
        )
        .expect("read table column identities");
    let defaults = fixture
        .execute(
            "SELECT column_name, column_default \
             FROM information_schema.columns \
             WHERE table_schema = 'issue_817_catalog_probe' \
               AND table_name = 'items' AND column_name = 'amount'",
        )
        .expect("read the stored column default");
    let constraints = fixture
        .execute(
            "SELECT conname, contype::text, convalidated \
             FROM pg_catalog.pg_constraint \
             WHERE conrelid = 'issue_817_catalog_probe.items'::regclass \
             ORDER BY conname",
        )
        .expect("read table constraints");
    let dependency = fixture
        .execute(
            "SELECT d.deptype::text, \
                    d.refobjid = 'issue_817_catalog_probe.items'::regclass, \
                    d.refobjsubid \
             FROM pg_catalog.pg_depend AS d \
             WHERE d.classid = 'pg_class'::regclass \
               AND d.refclassid = 'pg_class'::regclass \
               AND d.objid = pg_catalog.pg_get_serial_sequence( \
                   'issue_817_catalog_probe.items', 'id')::regclass",
        )
        .expect("read the identity sequence dependency");

    // Assert
    assert_eq!(
        relations.rows(),
        vec![
            vec![
                Value::String("items".to_owned()),
                Value::String("r".to_owned()),
                Value::String("p".to_owned()),
                Value::Bool(true),
            ],
            vec![
                Value::String("items_amount_idx".to_owned()),
                Value::String("i".to_owned()),
                Value::String("p".to_owned()),
                Value::Bool(true),
            ],
            vec![
                Value::String("items_id_seq".to_owned()),
                Value::String("S".to_owned()),
                Value::String("p".to_owned()),
                Value::Bool(true),
            ],
            vec![
                Value::String("items_pkey".to_owned()),
                Value::String("i".to_owned()),
                Value::String("p".to_owned()),
                Value::Bool(true),
            ],
        ]
    );
    assert_eq!(
        attributes.rows(),
        vec![
            vec![
                Value::String("id".to_owned()),
                Value::Int64(1),
                Value::Int64(23),
                Value::Int64(-1),
                Value::Bool(true),
                Value::String("d".to_owned()),
            ],
            vec![
                Value::String("amount".to_owned()),
                Value::Int64(2),
                Value::Int64(1_700),
                Value::Int64(458_758),
                Value::Bool(true),
                Value::String(String::new()),
            ],
        ]
    );
    assert_eq!(
        defaults.rows(),
        vec![vec![
            Value::String("amount".to_owned()),
            Value::String("1.25".to_owned()),
        ]]
    );
    assert_eq!(
        constraints.rows(),
        vec![
            vec![
                Value::String("issue_817_amount_positive".to_owned()),
                Value::String("c".to_owned()),
                Value::Bool(true),
            ],
            vec![
                Value::String("items_amount_not_null".to_owned()),
                Value::String("n".to_owned()),
                Value::Bool(true),
            ],
            vec![
                Value::String("items_id_not_null".to_owned()),
                Value::String("n".to_owned()),
                Value::Bool(true),
            ],
            vec![
                Value::String("items_pkey".to_owned()),
                Value::String("p".to_owned()),
                Value::Bool(true),
            ],
        ]
    );
    assert_eq!(
        dependency.rows(),
        vec![vec![
            Value::String("i".to_owned()),
            Value::Bool(true),
            Value::Int64(1),
        ]]
    );
}

