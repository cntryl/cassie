use super::{current_thread_runtime, PgwireFixture};

#[test]
fn should_commit_truncate_restart_identity_state() {
    // Arrange
    let runtime = current_thread_runtime();
    runtime.block_on(async {
        let fixture = PgwireFixture::start("issue-823-truncate-restart-identity-commit").await;
        fixture
            .client()
            .batch_execute(
                "CREATE TABLE issue_823_truncate_restart_identity ( \
                   id INTEGER GENERATED BY DEFAULT AS IDENTITY \
                 )",
            )
            .await
            .expect("create an identity-backed table");
        let first: i32 = fixture
            .client()
            .query_one(
                "INSERT INTO issue_823_truncate_restart_identity DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert the first identity value")
            .get(0);
        let second: i32 = fixture
            .client()
            .query_one(
                "INSERT INTO issue_823_truncate_restart_identity DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert the second identity value")
            .get(0);

        // Act
        fixture
            .client()
            .batch_execute("BEGIN")
            .await
            .expect("begin the truncate transaction");
        fixture
            .client()
            .batch_execute("TRUNCATE TABLE issue_823_truncate_restart_identity RESTART IDENTITY")
            .await
            .expect("restart the owned identity sequence");
        let restarted: i32 = fixture
            .client()
            .query_one(
                "INSERT INTO issue_823_truncate_restart_identity DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert after restarting the identity sequence")
            .get(0);
        fixture
            .client()
            .batch_execute("COMMIT")
            .await
            .expect("commit the table truncate and identity restart");
        let after_commit: i32 = fixture
            .client()
            .query_one(
                "INSERT INTO issue_823_truncate_restart_identity DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert after the identity restart commits")
            .get(0);
        fixture.shutdown().await;

        // Assert
        assert_eq!((first, second, restarted, after_commit), (1, 2, 1, 2));
    });
}
