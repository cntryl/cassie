//! Transaction-owned SERIAL and IDENTITY sequence visibility over PostgreSQL wire.

use crate::support_pgwire as wire;
use std::net::SocketAddr;
use std::time::Duration;

type Frames = Vec<(u8, Vec<u8>)>;

struct SequenceTables {
    serial: String,
    identity: String,
}

impl SequenceTables {
    fn new(prefix: &str) -> Self {
        Self {
            serial: format!("{prefix}_serial"),
            identity: format!("{prefix}_identity"),
        }
    }

    fn catalog_count_sql(&self) -> String {
        format!(
            "SELECT count(*) FROM pg_catalog.pg_class WHERE relname IN \
             ('{}', '{}_id_seq', '{}', '{}_id_seq')",
            self.serial, self.serial, self.identity, self.identity
        )
    }
}

struct WireSession {
    reader: tokio::net::tcp::OwnedReadHalf,
    writer: tokio::net::tcp::OwnedWriteHalf,
}

impl WireSession {
    async fn connect(address: SocketAddr) -> Self {
        let socket = tokio::net::TcpStream::connect(address)
            .await
            .expect("connect wire session");
        let (mut reader, mut writer) = socket.into_split();
        wire::complete_startup(&mut reader, &mut writer).await;
        Self { reader, writer }
    }

    async fn query(&mut self, sql: &str) -> Frames {
        wire::write_frames(&mut self.writer, vec![wire::simple_query_frame(sql)]).await;
        wire::read_frames_until_ready_within(&mut self.reader, Duration::from_secs(5)).await
    }
}

fn ready_status(frames: &Frames) -> Option<u8> {
    frames
        .iter()
        .find(|(tag, _)| *tag == b'Z')
        .and_then(|(_, body)| body.first().copied())
}

fn assert_success(frames: &Frames, expected_status: u8) {
    assert_eq!(wire::error_code(frames), None, "{frames:?}");
    assert_eq!(ready_status(frames), Some(expected_status), "{frames:?}");
}

fn assert_value(frames: &Frames, expected: &str, expected_status: u8) {
    assert_success(frames, expected_status);
    assert_eq!(
        wire::data_rows(frames),
        vec![vec![Some(expected.to_owned())]],
        "{frames:?}"
    );
}

fn assert_inserted_id(frames: &Frames, expected: &str, expected_status: u8) {
    assert_value(frames, expected, expected_status);
    assert_eq!(
        frames
            .iter()
            .find(|(tag, _)| *tag == b'C')
            .map(|(_, body)| body.as_slice()),
        Some(&b"INSERT 0 1\0"[..]),
        "{frames:?}"
    );
}

async fn assert_catalog_count(
    session: &mut WireSession,
    tables: &SequenceTables,
    expected: &str,
    expected_status: u8,
) {
    let frames = session.query(&tables.catalog_count_sql()).await;
    assert_value(&frames, expected, expected_status);
}

async fn assert_ids(session: &mut WireSession, table: &str, ids: &[&str], expected_status: u8) {
    let frames = session
        .query(&format!("SELECT id FROM {table} ORDER BY id"))
        .await;
    assert_success(&frames, expected_status);
    assert_eq!(
        wire::data_rows(&frames),
        ids.iter()
            .map(|id| vec![Some((*id).to_owned())])
            .collect::<Vec<_>>(),
        "{frames:?}"
    );
}

async fn create_tables(session: &mut WireSession, tables: &SequenceTables, expected_status: u8) {
    assert_success(
        &session
            .query(&format!(
                "CREATE TABLE {} (id SERIAL PRIMARY KEY)",
                tables.serial
            ))
            .await,
        expected_status,
    );
    assert_success(
        &session
            .query(&format!(
                "CREATE TABLE {} \
                 (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)",
                tables.identity
            ))
            .await,
        expected_status,
    );
}

async fn assert_staged_visibility(
    owner: &mut WireSession,
    observer: &mut WireSession,
    tables: &SequenceTables,
) {
    assert_catalog_count(owner, tables, "4", b'T').await;
    assert_catalog_count(observer, tables, "0", b'I').await;
}

async fn exercise_direct_values_and_defaults(
    owner: &mut WireSession,
    tables: &SequenceTables,
    expected_status: u8,
    direct_value: &str,
    default_value: &str,
) {
    for table in [&tables.serial, &tables.identity] {
        assert_value(
            &owner
                .query(&format!("SELECT nextval('{table}_id_seq')"))
                .await,
            direct_value,
            expected_status,
        );
        assert_inserted_id(
            &owner
                .query(&format!("INSERT INTO {table} DEFAULT VALUES RETURNING id"))
                .await,
            default_value,
            expected_status,
        );
    }
}

async fn assert_savepoint_cursor_behavior(
    owner: &mut WireSession,
    observer: &mut WireSession,
    tables: &SequenceTables,
) {
    assert_success(&owner.query("SAVEPOINT sequence_cursor").await, b'T');
    exercise_direct_values_and_defaults(owner, tables, b'T', "3", "4").await;
    assert_success(
        &owner.query("ROLLBACK TO SAVEPOINT sequence_cursor").await,
        b'T',
    );
    for table in [&tables.serial, &tables.identity] {
        assert_value(
            &owner
                .query(&format!("SELECT nextval('{table}_id_seq')"))
                .await,
            "5",
            b'T',
        );
        assert_ids(owner, table, &["2"], b'T').await;
    }
    assert_catalog_count(observer, tables, "0", b'I').await;
}

async fn recover_expected_transaction_error(owner: &mut WireSession) {
    assert_success(&owner.query("SAVEPOINT before_expected_error").await, b'T');
    let failed = owner.query("SELECT 1 / 0").await;
    assert_eq!(wire::error_code(&failed).as_deref(), Some("22012"));
    assert_eq!(ready_status(&failed), Some(b'E'));
    assert_success(
        &owner
            .query("ROLLBACK TO SAVEPOINT before_expected_error")
            .await,
        b'T',
    );
}

async fn commit_and_check_observer(
    owner: &mut WireSession,
    observer: &mut WireSession,
    tables: &SequenceTables,
) {
    assert_success(&owner.query("COMMIT").await, b'I');
    assert_catalog_count(observer, tables, "4", b'I').await;
    for table in [&tables.serial, &tables.identity] {
        assert_ids(observer, table, &["2"], b'I').await;
        assert_value(
            &observer
                .query(&format!("SELECT nextval('{table}_id_seq')"))
                .await,
            "6",
            b'I',
        );
    }
}

async fn assert_full_rollback_and_recreation(
    owner: &mut WireSession,
    observer: &mut WireSession,
    suffix: &str,
    isolation: &str,
) {
    let tables = SequenceTables::new(&format!("owned_sequence_{suffix}_rolled"));
    assert_success(
        &owner
            .query(&format!("BEGIN ISOLATION LEVEL {isolation}"))
            .await,
        b'T',
    );
    create_tables(owner, &tables, b'T').await;
    exercise_direct_values_and_defaults(owner, &tables, b'T', "1", "2").await;
    assert_staged_visibility(owner, observer, &tables).await;
    assert_success(&owner.query("ROLLBACK").await, b'I');
    assert_catalog_count(owner, &tables, "0", b'I').await;
    assert_catalog_count(observer, &tables, "0", b'I').await;

    create_tables(owner, &tables, b'I').await;
    for table in [&tables.serial, &tables.identity] {
        assert_inserted_id(
            &owner
                .query(&format!("INSERT INTO {table} DEFAULT VALUES RETURNING id"))
                .await,
            "1",
            b'I',
        );
    }
}

async fn run_isolation_profile(suffix: &str, isolation: &str) {
    let cassie = crate::support_sql::new_in_memory_cassie().expect("memory fixture");
    cassie.startup().expect("startup");
    let server = wire::spawn_server(cassie).await;
    let mut owner = WireSession::connect(server.addr).await;
    let mut observer = WireSession::connect(server.addr).await;
    let tables = SequenceTables::new(&format!("owned_sequence_{suffix}"));

    assert_value(&owner.query("SELECT 1").await, "1", b'I');
    assert_value(&observer.query("SELECT 1").await, "1", b'I');
    assert_success(
        &owner
            .query(&format!("BEGIN ISOLATION LEVEL {isolation}"))
            .await,
        b'T',
    );
    create_tables(&mut owner, &tables, b'T').await;
    assert_staged_visibility(&mut owner, &mut observer, &tables).await;
    exercise_direct_values_and_defaults(&mut owner, &tables, b'T', "1", "2").await;
    assert_savepoint_cursor_behavior(&mut owner, &mut observer, &tables).await;
    recover_expected_transaction_error(&mut owner).await;
    commit_and_check_observer(&mut owner, &mut observer, &tables).await;
    assert_full_rollback_and_recreation(&mut owner, &mut observer, suffix, isolation).await;

    drop((owner, observer));
    server.stop().await;
}

#[test]
fn should_publish_transaction_owned_sequences_across_isolation_levels() {
    // Arrange
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("current-thread runtime");

    // Act
    let completed = runtime.block_on(async {
        let mut completed = Vec::new();
        for (suffix, isolation) in [
            ("rc", "READ COMMITTED"),
            ("rr", "REPEATABLE READ READ WRITE"),
        ] {
            run_isolation_profile(suffix, isolation).await;
            completed.push(suffix);
        }
        completed
    });

    // Assert
    assert_eq!(completed, ["rc", "rr"]);
}
