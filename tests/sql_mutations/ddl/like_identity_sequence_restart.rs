//! LIKE identity clones retain independent owned sequences after restart.
use cassie::app::{Cassie, CassieSession};
use cassie::catalog::SequenceMeta;
use cassie::types::Value;

use crate::support_catalog_directory::CatalogDirectory;

fn execute(cassie: &Cassie, session: &CassieSession, sql: &str) {
    cassie
        .execute_sql(session, sql, vec![])
        .unwrap_or_else(|error| panic!("execute {sql}: {error}"));
}

fn returned_id(cassie: &Cassie, session: &CassieSession, sql: &str) -> i64 {
    let result = cassie
        .execute_sql(session, sql, vec![])
        .unwrap_or_else(|error| panic!("execute {sql}: {error}"));
    match result.rows() {
        [row] => match row.as_slice() {
            [Value::Int64(value)] => *value,
            values => panic!("expected one BIGINT identity, got {values:?}"),
        },
        rows => panic!("expected one inserted row, got {rows:?}"),
    }
}

fn owned_identity(cassie: &Cassie, sequence: &str, table: &str) -> SequenceMeta {
    let metadata = cassie
        .catalog
        .get_sequence(sequence)
        .unwrap_or_else(|| panic!("missing identity sequence {sequence}"));
    assert_eq!(metadata.start_value, 5);
    assert_eq!(metadata.increment_by, 2);
    let owner = metadata
        .owned_by
        .as_ref()
        .unwrap_or_else(|| panic!("identity sequence {sequence} is not owned"));
    assert_eq!(owner.table, cassie.midge.canonical_collection_name(table));
    assert_eq!(owner.column, "id");
    metadata
}

#[test]
fn should_recover_independent_owned_identity_sequences_after_local_restart() {
    // Arrange
    let directory = CatalogDirectory::new("like-identity-sequence-restart");
    let before_restart;
    {
        let cassie = Cassie::new_with_data_dir_and_config(
            &directory.0,
            cassie::config::CassieRuntimeConfig::default(),
        )
        .expect("create local-storage Cassie");
        cassie.startup().expect("start local-storage Cassie");
        let session = cassie.create_session("tester", None);
        execute(
            &cassie,
            &session,
            "CREATE TABLE clone_identity_source (\
               id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 5 INCREMENT BY 2),\
               label TEXT\
             )",
        );

        // Seed identity sequences before the restart
        execute(
            &cassie,
            &session,
            "CREATE TABLE clone_identity_target \
             (LIKE clone_identity_source INCLUDING IDENTITY)",
        );
        assert_eq!(
            returned_id(
                &cassie,
                &session,
                "INSERT INTO clone_identity_source (label) \
                 VALUES ('source before restart') RETURNING id",
            ),
            5
        );
        assert_eq!(
            returned_id(
                &cassie,
                &session,
                "INSERT INTO clone_identity_target (label) \
                 VALUES ('target before restart') RETURNING id",
            ),
            5
        );
        let source_sequence = owned_identity(
            &cassie,
            "clone_identity_source_id_seq",
            "clone_identity_source",
        );
        let target_sequence = owned_identity(
            &cassie,
            "clone_identity_target_id_seq",
            "clone_identity_target",
        );
        assert_ne!(source_sequence.object_id, target_sequence.object_id);
        before_restart = [source_sequence.object_id, target_sequence.object_id];
    }

    // Act
    let cassie = Cassie::new_with_data_dir_and_config(
        &directory.0,
        cassie::config::CassieRuntimeConfig::default(),
    )
    .expect("reopen local-storage Cassie");
    cassie.startup().expect("recover local-storage Cassie");
    let session = cassie.create_session("tester", None);
    let source_sequence = owned_identity(
        &cassie,
        "clone_identity_source_id_seq",
        "clone_identity_source",
    );
    let target_sequence = owned_identity(
        &cassie,
        "clone_identity_target_id_seq",
        "clone_identity_target",
    );

    // Assert
    assert_eq!(
        [source_sequence.object_id, target_sequence.object_id],
        before_restart
    );
    assert_eq!(
        returned_id(
            &cassie,
            &session,
            "INSERT INTO clone_identity_source (label) \
             VALUES ('source after restart') RETURNING id",
        ),
        7
    );
    assert_eq!(
        returned_id(
            &cassie,
            &session,
            "INSERT INTO clone_identity_target (label) \
             VALUES ('target after restart') RETURNING id",
        ),
        7
    );
}
