//! Explicit NULL is nullable syntax, with conflicting declarations rejected.

use crate::support_pgwire as wire;
use std::time::Duration;

fn nullability_cycles(conflicting: bool) {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("current-thread runtime");
    runtime.block_on(async {
        let cassie = crate::support_sql::new_in_memory_cassie().expect("memory fixture");
        cassie.startup().expect("startup");
        let server = wire::spawn_server(cassie).await;
        let declarations: &[(&str, bool)] = if conflicting {
            &[
                ("TEXT NULL NOT NULL", true),
                ("TEXT PRIMARY KEY NULL", true),
                ("SERIAL NULL", true),
                ("INTEGER GENERATED BY DEFAULT AS IDENTITY NULL", true),
            ]
        } else {
            &[
                ("TEXT NULL", true),
                ("TEXT CONSTRAINT nullable_value NULL UNIQUE", true),
                ("TEXT NULL, PRIMARY KEY (value)", false),
            ]
        };
        for extended in [false, true] {
            for (index, (declaration, nullable)) in declarations.iter().enumerate() {
                let connection = tokio::net::TcpStream::connect(server.addr)
                    .await
                    .expect("connection");
                let (mut reader, mut writer) = connection.into_split();
                wire::complete_startup(&mut reader, &mut writer).await;
                let name = format!("wire_null_{extended}_{conflicting}_{index}");
                let sql = format!("CREATE TABLE {name} (value {declaration})");
                let frames = if extended {
                    vec![
                        wire::parse_frame("nullable", &sql),
                        wire::bind_frame("", "nullable", &[]),
                        wire::execute_frame(""),
                        wire::sync_frame(),
                    ]
                } else {
                    vec![wire::simple_query_frame(&sql)]
                };

                // Act
                wire::write_frames(&mut writer, frames).await;
                let result =
                    wire::read_frames_until_ready_within(&mut reader, Duration::from_secs(10))
                        .await;
                let inspect = if conflicting {
                    format!("SELECT count(*) FROM pg_class WHERE relname = '{name}'")
                } else {
                    wire::write_frames(
                        &mut writer,
                        vec![wire::simple_query_frame(&format!(
                            "ALTER TABLE {name} ADD COLUMN additional TEXT NULL"
                        ))],
                    )
                    .await;
                    let altered =
                        wire::read_frames_until_ready_within(&mut reader, Duration::from_secs(10))
                            .await;
                    assert_eq!(wire::error_code(&altered), None);
                    let value = if *nullable { "NULL" } else { "'kept'" };
                    wire::write_frames(
                        &mut writer,
                        vec![wire::simple_query_frame(&format!(
                            "INSERT INTO {name} VALUES ({value}, NULL)"
                        ))],
                    )
                    .await;
                    let inserted =
                        wire::read_frames_until_ready_within(&mut reader, Duration::from_secs(10))
                            .await;
                    assert_eq!(wire::error_code(&inserted), None);
                    format!("SELECT value, additional FROM {name}")
                };
                wire::write_frames(&mut writer, vec![wire::simple_query_frame(&inspect)]).await;
                let observed =
                    wire::read_frames_until_ready_within(&mut reader, Duration::from_secs(10))
                        .await;

                // Assert
                assert_eq!(
                    result.last().map(|(_, body)| body.as_slice()),
                    Some(&b"I"[..])
                );
                if conflicting {
                    assert_eq!(wire::error_code(&result).as_deref(), Some("42601"));
                    assert!(result.iter().all(|(tag, _)| *tag != b'C'));
                    assert_eq!(wire::data_rows(&observed), vec![vec![Some("0".to_owned())]]);
                } else {
                    assert_eq!(wire::error_code(&result), None);
                    let expected = (!*nullable).then(|| "kept".to_owned());
                    assert_eq!(wire::data_rows(&observed), vec![vec![expected, None]]);
                }
                assert_eq!(wire::error_code(&observed), None);
            }
        }
        server.stop().await;
    });
}

#[test]
fn should_store_explicit_null_columns_in_both_wire_protocols() {
    // Arrange
    let conflicting = false;
    // Act
    nullability_cycles(conflicting);
    // Assert
    // Each protocol must accept both the declaration and a NULL row value.
}

#[test]
fn should_reject_conflicting_nullability_in_both_wire_protocols() {
    // Arrange
    let conflicting = true;
    // Act
    nullability_cycles(conflicting);
    // Assert
    // Each protocol must return 42601, ReadyForQuery(I), and publish no relation.
}
