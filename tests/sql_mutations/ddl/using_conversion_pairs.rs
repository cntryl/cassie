//! The finite `ALTER COLUMN ... TYPE ... USING` conversion pairs qualified for v0.2.0.
//!
//! `{c}` in a USING template stands for the converted column. The expected text
//! and type are the post-rewrite `c::text` and `pg_typeof(c)::text` of one row
//! whose source value is `literal`.

pub struct Pair {
    pub from: &'static str,
    pub literal: &'static str,
    pub to: &'static str,
    pub using: &'static str,
    pub value: &'static str,
    pub type_name: &'static str,
}

const fn pair(
    from: &'static str,
    literal: &'static str,
    to: &'static str,
    using: &'static str,
    value: &'static str,
    type_name: &'static str,
) -> Pair {
    Pair {
        from,
        literal,
        to,
        using,
        value,
        type_name,
    }
}

