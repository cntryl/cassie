#[test]
fn should_move_quoted_owned_sequence_with_table_schema() {
    // Arrange
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("runtime");

    runtime.block_on(async {
        let cassie = crate::support_sql::new_in_memory_cassie().expect("create Cassie");
        cassie.startup().expect("startup");
        let session = cassie.create_session("tester", None);
        for sql in [
            "CREATE SCHEMA \"MoveSource\"",
            "CREATE SCHEMA \"MoveTarget\"",
            "CREATE SEQUENCE \"MoveSource\".\"OrderIds\"",
            "CREATE TABLE \"MoveSource\".orders (id BIGINT DEFAULT nextval('\"MoveSource\".\"OrderIds\"'::regclass))",
            "ALTER SEQUENCE \"MoveSource\".\"OrderIds\" OWNED BY \"MoveSource\".orders.id",
            "INSERT INTO \"MoveSource\".orders DEFAULT VALUES",
        ] {
            execute_statement(&cassie, &session, sql);
        }
        let source_sequence = "\"MoveSource\".\"OrderIds\"";
        let target_sequence = "\"MoveTarget\".\"OrderIds\"";

        // Act
        execute_statement(
            &cassie,
            &session,
            "ALTER TABLE \"MoveSource\".orders SET SCHEMA \"MoveTarget\"",
        );
        execute_statement(
            &cassie,
            &session,
            "INSERT INTO \"MoveTarget\".orders DEFAULT VALUES",
        );

        // Assert
        assert!(!cassie.catalog.sequence_exists(source_sequence));
        let sequence = cassie
            .catalog
            .get_sequence(target_sequence)
            .expect("quoted owned sequence after schema move");
        assert_eq!(
            sequence
                .owned_by
                .as_ref()
                .map(|owner| owner.table.as_str()),
            Some("postgres.MoveTarget.orders")
        );
        assert_eq!(
            query_rows(
                &cassie,
                &session,
                "SELECT id FROM \"MoveTarget\".orders ORDER BY id"
            ),
            vec![vec![Value::Int64(1)], vec![Value::Int64(2)]]
        );
    });
}

#[test]
fn should_move_serial_sequence_without_sequence_owner_metadata() {
    // Arrange
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("runtime");

    runtime.block_on(async {
        let cassie = crate::support_sql::new_in_memory_cassie().expect("create Cassie");
        cassie.startup().expect("startup");
        let session = cassie.create_session("tester", None);
        for sql in [
            "CREATE SCHEMA legacy_source",
            "CREATE SCHEMA legacy_target",
            "CREATE TABLE legacy_source.orders (id SERIAL)",
            "INSERT INTO legacy_source.orders DEFAULT VALUES",
        ] {
            execute_statement(&cassie, &session, sql);
        }
        let mut sequence = cassie
            .catalog
            .get_sequence("legacy_source.orders_id_seq")
            .expect("SERIAL sequence");
        sequence.owned_by = None;
        cassie
            .midge
            .put_sequence(&sequence)
            .expect("store legacy sequence metadata without owned_by");
        cassie.catalog.register_sequence(sequence);

        // Act
        execute_statement(
            &cassie,
            &session,
            "ALTER TABLE legacy_source.orders SET SCHEMA legacy_target",
        );
        execute_statement(
            &cassie,
            &session,
            "INSERT INTO legacy_target.orders DEFAULT VALUES",
        );

        // Assert
        let sequence = cassie
            .catalog
            .get_sequence("legacy_target.orders_id_seq")
            .expect("moved legacy SERIAL sequence");
        assert!(sequence.owned_by.is_none());
        assert!(!cassie
            .catalog
            .sequence_exists("legacy_source.orders_id_seq"));
        assert_eq!(
            query_rows(
                &cassie,
                &session,
                "SELECT id FROM legacy_target.orders ORDER BY id"
            ),
            vec![vec![Value::Int64(1)], vec![Value::Int64(2)]]
        );
    });
}

