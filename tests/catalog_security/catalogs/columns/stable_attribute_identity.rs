//! Stable PostgreSQL attribute identities backed by Midge row metadata for #817.

use crate::support_sql_fixture::sql_fixture;
use cassie::app::{Cassie, CassieSession};
use cassie::config::CassieRuntimeConfig;
use cassie::types::Value;

#[test]
fn should_keep_attribute_identity_across_schema_evolution() {
    // Arrange
    let fixture = sql_fixture(
        "issue-817-stable-attribute-identity",
        &["CREATE TABLE issue_817_stable_attributes (\
                first_col TEXT, \
                removed_col VARCHAR(7) NOT NULL DEFAULT 'retired', \
                identity_col BIGINT GENERATED BY DEFAULT AS IDENTITY, \
                renamed_col BOOLEAN, \
                catalog_name NAME, labels TEXT[]\
            )"],
    );
    fixture.cassie.startup().expect("startup");
    for sql in [
        "ALTER TABLE issue_817_stable_attributes DROP COLUMN removed_col",
        "ALTER TABLE issue_817_stable_attributes DROP COLUMN identity_col",
        "ALTER TABLE issue_817_stable_attributes RENAME COLUMN renamed_col TO renamed_again",
        "ALTER TABLE issue_817_stable_attributes ADD COLUMN added_col TEXT",
    ] {
        fixture
            .execute(sql)
            .unwrap_or_else(|error| panic!("schema evolution failed: {sql}: {error:?}"));
    }

    // Act
    let attributes = fixture
        .execute(
            "SELECT attname, attnum, attisdropped, atttypid, atttypmod, attcollation, \
                    attnotnull, atthasdef, attidentity, attgenerated \
             FROM pg_catalog.pg_attribute \
             WHERE attrelid = 'issue_817_stable_attributes' AND attnum > 0 \
             ORDER BY attnum",
        )
        .expect("read stable attribute identities");
    let collations = fixture
        .execute(
            "SELECT oid, collname, collprovider FROM pg_catalog.pg_collation \
             WHERE oid IN (100, 950) ORDER BY oid",
        )
        .expect("read the default and C collation identities");

    // Assert
    assert_eq!(
        attributes.rows(),
        vec![
            attribute_row("first_col", 1, false, 25, -1, 100),
            attribute_row("........pg.dropped.2........", 2, true, 0, 11, 100),
            attribute_row("........pg.dropped.3........", 3, true, 0, -1, 0),
            attribute_row("renamed_again", 4, false, 16, -1, 0),
            attribute_row("catalog_name", 5, false, 19, -1, 950),
            attribute_row("labels", 6, false, 1009, -1, 100),
            attribute_row("added_col", 7, false, 25, -1, 100),
        ]
    );
    assert_eq!(
        collations.rows(),
        vec![
            vec![
                Value::Int64(100),
                Value::String("default".to_owned()),
                Value::String("d".to_owned()),
            ],
            vec![
                Value::Int64(950),
                Value::String("C".to_owned()),
                Value::String("c".to_owned()),
            ],
        ]
    );
}

#[test]
fn should_preserve_attribute_identity_after_local_restart() {
    // Arrange
    let directory = crate::support_catalog_directory::CatalogDirectory::new(
        "issue-817-attribute-identity-restart",
    );
    let config = crate::support_sql::with_test_root_password(CassieRuntimeConfig::default());
    let expected = vec![
        vec![
            Value::String("payload".to_owned()),
            Value::Int64(1),
            Value::Bool(false),
            Value::Int64(1043),
            Value::Int64(13),
            Value::Int64(100),
        ],
        vec![
            Value::String("........pg.dropped.2........".to_owned()),
            Value::Int64(2),
            Value::Bool(true),
            Value::Int64(0),
            Value::Int64(-1),
            Value::Int64(100),
        ],
        vec![
            Value::String("current_name".to_owned()),
            Value::Int64(3),
            Value::Bool(false),
            Value::Int64(16),
            Value::Int64(-1),
            Value::Int64(0),
        ],
        vec![
            Value::String("added".to_owned()),
            Value::Int64(4),
            Value::Bool(false),
            Value::Int64(25),
            Value::Int64(-1),
            Value::Int64(100),
        ],
    ];
    let query = "SELECT attname, attnum, attisdropped, atttypid, atttypmod, attcollation \
                 FROM pg_catalog.pg_attribute \
                 WHERE attrelid = 'issue_817_restart_attributes' AND attnum > 0 \
                 ORDER BY attnum";

    // Act
    {
        let cassie = Cassie::new_with_data_dir_and_config(&directory.0, config.clone())
            .expect("create the local catalog instance");
        cassie.startup().expect("start the local catalog instance");
        let session = cassie.create_session("tester", None);
        for sql in [
            "CREATE TABLE issue_817_restart_attributes (payload VARCHAR(9), old_name TEXT, current BOOLEAN)",
            "ALTER TABLE issue_817_restart_attributes DROP COLUMN old_name",
            "ALTER TABLE issue_817_restart_attributes RENAME COLUMN current TO current_name",
            "ALTER TABLE issue_817_restart_attributes ADD COLUMN added TEXT",
        ] {
            cassie
                .execute_sql(&session, sql, vec![])
                .unwrap_or_else(|error| panic!("schema change failed: {sql}: {error}"));
        }
        let before_restart = cassie
            .execute_sql(&session, query, vec![])
            .expect("read stable identities before restart");
        assert_eq!(before_restart.rows(), expected);
        drop(session);
        cassie.shutdown();
    }

    let reopened = Cassie::new_with_data_dir_and_config(&directory.0, config)
        .expect("reopen the local catalog instance");
    reopened.startup().expect("start the reopened instance");
    let session: CassieSession = reopened.create_session("tester", None);
    let after_restart = reopened
        .execute_sql(&session, query, vec![])
        .expect("read stable identities after restart");

    // Assert
    assert_eq!(after_restart.rows(), expected);
    drop(session);
    reopened.shutdown();
}

/// Builds an expected `pg_attribute` row for a column without NOT NULL,
/// defaults, identity, or generation.
fn attribute_row(
    name: &str,
    attnum: i64,
    dropped: bool,
    type_oid: i64,
    typmod: i64,
    collation: i64,
) -> Vec<Value> {
    vec![
        Value::String(name.to_owned()),
        Value::Int64(attnum),
        Value::Bool(dropped),
        Value::Int64(type_oid),
        Value::Int64(typmod),
        Value::Int64(collation),
        Value::Bool(false),
        Value::Bool(false),
        Value::String(String::new()),
        Value::String(String::new()),
    ]
}
