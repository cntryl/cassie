//! Selected #826/#839 DDL forms with a catalog probe that flips when the form publishes.

pub struct Form {
    pub name: &'static str,
    pub setup: &'static [&'static str],
    pub ddl: &'static str,
    pub probe: &'static str,
    pub before: &'static str,
    pub after: &'static str,
    pub tag: &'static str,
    /// Whether an explicit transaction stages this form; otherwise it is standalone only.
    pub explicit: bool,
}

const SOURCE: &str = "CREATE TABLE src (id INT PRIMARY KEY, label TEXT DEFAULT 'x' NOT NULL)";
const SOURCE_ROW: &str = "INSERT INTO src VALUES (1, 'one')";

macro_rules! rel {
    ($name:literal) => {
        concat!(
            "SELECT count(*) FROM pg_class WHERE relname = '",
            $name,
            "'"
        )
    };
}

macro_rules! col {
    ($table:literal, $column:literal) => {
        concat!(
            "SELECT count(*) FROM information_schema.columns WHERE table_name = '",
            $table,
            "' AND column_name = '",
            $column,
            "'"
        )
    };
}

macro_rules! constraint {
    ($name:literal) => {
        concat!(
            "SELECT count(*) FROM pg_constraint WHERE conname = '",
            $name,
            "'"
        )
    };
}

const fn form(
    name: &'static str,
    setup: &'static [&'static str],
    ddl: &'static str,
    probe: &'static str,
    (before, after): (&'static str, &'static str),
    tag: &'static str,
) -> Form {
    Form {
        name,
        setup,
        ddl,
        probe,
        before,
        after,
        tag,
        explicit: true,
    }
}

const fn standalone(mut form: Form) -> Form {
    form.explicit = false;
    form
}

