use crate::sql::ast::{FieldDefinition, QueryStatement};

fn first_field(definition: &str) -> FieldDefinition {
    let sql = format!("CREATE TABLE nullability_probe ({definition})");
    let parsed = crate::sql::parse_statement(&sql).expect("nullable column declaration");
    let QueryStatement::CreateTable(table) = parsed.statement else {
        panic!("expected CREATE TABLE");
    };
    table.fields.into_iter().next().expect("one field")
}

#[test]
fn should_accept_explicit_null_without_adding_not_null_ownership() {
    // Arrange
    let declarations = [
        "value TEXT NULL",
        "value TEXT NULL NULL",
        "value TEXT NULL DEFAULT NULL",
        "value TEXT NULL UNIQUE",
        "value TEXT CONSTRAINT nullable_value NULL",
    ];

    // Act
    let fields = declarations.map(first_field);

    // Assert
    for field in fields {
        assert!(field
            .constraints
            .iter()
            .all(|constraint| !constraint.not_null));
    }
}

#[test]
fn should_reject_explicit_null_with_any_not_null_owner() {
    // Arrange
    let declarations = [
        "value TEXT NOT NULL NULL",
        "value TEXT NULL NOT NULL",
        "value TEXT PRIMARY KEY NULL",
        "value TEXT NULL PRIMARY KEY",
        "value SERIAL NULL",
        "value INTEGER GENERATED BY DEFAULT AS IDENTITY NULL",
        "value INTEGER NULL GENERATED ALWAYS AS IDENTITY",
    ];

    // Act
    let errors = declarations.map(|definition| {
        let sql = format!("CREATE TABLE nullability_probe ({definition})");
        crate::sql::parse_statement(&sql).expect_err("conflicting nullability")
    });

    // Assert
    for error in errors {
        assert!(error.to_string().contains("conflicting NULL/NOT NULL"));
    }
}

#[test]
fn should_allow_table_primary_key_to_supply_not_null_after_explicit_null() {
    // Arrange
    let declaration = "value TEXT NULL, PRIMARY KEY (value)";

    // Act
    let field = first_field(declaration);

    // Assert
    let primary = field
        .constraints
        .iter()
        .find(|constraint| constraint.primary_key)
        .expect("table primary key");
    assert!(primary.not_null);
    assert!(!primary.not_null_ownership.is_explicit());
}

#[test]
fn should_consume_null_constraint_names_before_the_next_constraint() {
    // Arrange
    let declarations = [
        ("value TEXT CONSTRAINT nullable_value NULL UNIQUE", None),
        (
            "value TEXT CONSTRAINT nullable_value NULL CONSTRAINT unique_value UNIQUE",
            Some("unique_value"),
        ),
    ];

    // Act
    let unique_names = declarations.map(|(definition, expected)| {
        let field = first_field(definition);
        let unique = field
            .constraints
            .iter()
            .find(|constraint| constraint.unique)
            .expect("unique constraint");
        (unique.unique_name.clone(), expected)
    });

    // Assert
    for (actual, expected) in unique_names {
        assert_eq!(actual.as_deref(), expected);
    }
}

#[test]
fn should_consume_null_names_before_following_constraint_families() {
    // Arrange
    let declarations = [
        "value TEXT CONSTRAINT nullable_value NULL CHECK (value <> 'blocked')",
        "value TEXT CONSTRAINT nullable_value NULL REFERENCES parent(value)",
    ];

    // Act
    let constraints = declarations.map(|declaration| {
        first_field(declaration)
            .constraints
            .into_iter()
            .next()
            .expect("constraint")
    });

    // Assert
    assert!(constraints[0].check.is_some());
    assert_eq!(constraints[0].check_name, None);
    assert!(constraints[1].references_table.is_some());
    assert_eq!(constraints[1].foreign_key_name, None);
}
