#[test]
fn should_report_identity_column_metadata_in_information_schema() {
    // Arrange
    let fixture = sql_fixture(
        "issue-817-information-schema-column-generation",
        &["CREATE TABLE issue_817_identity_columns (id INTEGER)"],
    );
    fixture.cassie.startup().expect("startup");

    // Act
    let selected = fixture
        .execute(
            "SELECT column_name, is_identity, identity_generation, is_generated \
             FROM information_schema.columns \
             WHERE table_schema = 'public' \
               AND table_name = 'issue_817_identity_columns' \
             ORDER BY ordinal_position",
        )
        .expect("read identity and generation metadata");

    // Assert
    assert_eq!(
        selected.rows(),
        vec![vec![
            Value::String("id".to_owned()),
            Value::String("NO".to_owned()),
            Value::Null,
            Value::String("NEVER".to_owned()),
        ]]
    );
}

#[test]
fn should_report_pg_attribute_identity_generation_through_alterations() {
    // Arrange
    let fixture = sql_fixture("issue-817-attidentity", &["CREATE TABLE issue_817_attidentity (always_id INT GENERATED ALWAYS AS IDENTITY, default_id BIGINT GENERATED BY DEFAULT AS IDENTITY, serial_id SERIAL, plain TEXT)"]);
    fixture.cassie.startup().expect("startup");
    let query = "SELECT attname, attidentity::text FROM pg_catalog.pg_attribute WHERE attrelid = 'issue_817_attidentity' AND attnum > 0 ORDER BY attnum";
    let before = fixture.execute(query).expect("initial identity metadata");

    // Act
    fixture
        .execute(
            "ALTER TABLE issue_817_attidentity ALTER COLUMN always_id SET GENERATED BY DEFAULT",
        )
        .expect("change generation mode");
    fixture
        .execute("ALTER TABLE issue_817_attidentity ALTER COLUMN default_id DROP IDENTITY")
        .expect("drop identity");
    let after = fixture.execute(query).expect("altered identity metadata");

    // Assert
    let expected = |first: &str, second: &str| {
        [
            ("always_id", first),
            ("default_id", second),
            ("serial_id", ""),
            ("plain", ""),
        ]
        .map(|(name, identity)| vec![Value::String(name.into()), Value::String(identity.into())])
        .to_vec()
    };
    assert_eq!(before.rows(), expected("a", "d"));
    assert_eq!(after.rows(), expected("d", ""));
}

#[test]
fn should_preserve_pg_attribute_identity_metadata_after_local_restart() {
    // Arrange
    let directory = crate::support_temp_dirs::IsolatedDataDir::new("issue-817-attidentity-restart");
    let config =
        crate::support_sql::with_test_root_password(cassie::config::CassieRuntimeConfig::default());
    {
        let cassie = cassie::app::Cassie::new_local_with_data_dir_and_config(
            directory.path(),
            config.clone(),
        )
        .expect("open local Cassie");
        cassie.startup().expect("startup");
        let session = cassie.create_session("tester", None);
        cassie.execute_sql(&session, "CREATE TABLE issue_817_attidentity_restart (id BIGINT GENERATED BY DEFAULT AS IDENTITY, ordinary TEXT)", vec![]).expect("create table");
        drop(session);
        cassie.shutdown();
    }

    // Act
    let reopened =
        cassie::app::Cassie::new_local_with_data_dir_and_config(directory.path(), config)
            .expect("reopen local Cassie");
    reopened.startup().expect("recover");
    let session = reopened.create_session("tester", None);
    let selected = reopened.execute_sql(&session, "SELECT attname, attidentity::text FROM pg_catalog.pg_attribute WHERE attrelid = 'issue_817_attidentity_restart' AND attnum > 0 ORDER BY attnum", vec![]).expect("read identity metadata");

    // Assert
    assert_eq!(
        selected.rows(),
        vec![
            vec![Value::String("id".into()), Value::String("d".into())],
            vec![
                Value::String("ordinary".into()),
                Value::String(String::new())
            ]
        ]
    );
    drop(session);
    reopened.shutdown();
}

