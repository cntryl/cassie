fn execute_statement(cassie: &Cassie, session: &CassieSession, sql: &str) {
    cassie
        .execute_sql(session, sql, vec![])
        .unwrap_or_else(|error| panic!("execute {sql}: {error}"));
}

fn query_rows(cassie: &Cassie, session: &CassieSession, sql: &str) -> Vec<Vec<Value>> {
    cassie
        .execute_sql(session, sql, vec![])
        .unwrap()
        .rows()
        .to_vec()
}

#[test]
fn should_move_explicitly_owned_sequence_with_table_schema() {
    // Arrange
    use_local_storage();
    let path = data_dir("table_schema_owned_sequence_move");
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("runtime");

    runtime.block_on(async {
        let cassie = Cassie::new_with_data_dir(&path).expect("create Cassie");
        cassie.startup().expect("startup");
        let session = cassie.create_session("tester", None);
        for sql in [
            "CREATE SCHEMA move_source",
            "CREATE SCHEMA move_target",
            "CREATE SEQUENCE move_source.order_ids",
            "CREATE TABLE move_source.orders (id BIGINT DEFAULT nextval('move_source.order_ids'::regclass), generated_id BIGINT GENERATED BY DEFAULT AS IDENTITY, serial_id SERIAL)",
            "ALTER SEQUENCE move_source.order_ids OWNED BY move_source.orders.id",
            "INSERT INTO move_source.orders DEFAULT VALUES",
        ] {
            execute_statement(&cassie, &session, sql);
        }
        execute_statement(&cassie, &session, "BEGIN");
        execute_statement(
            &cassie,
            &session,
            "ALTER TABLE move_source.orders SET SCHEMA move_target",
        );
        execute_statement(&cassie, &session, "ROLLBACK");
        let custom_sequence_id = cassie
            .catalog
            .get_sequence("move_source.order_ids")
            .expect("explicit owned sequence before move")
            .object_id;
        let identity_sequence_id = cassie
            .catalog
            .get_sequence("move_source.orders_generated_id_seq")
            .expect("identity sequence before move")
            .object_id;
        let serial_sequence_id = cassie
            .catalog
            .get_sequence("move_source.orders_serial_id_seq")
            .expect("serial sequence before move")
            .object_id;

        // Assert
        assert_rollback_keeps_owned_sequences(&cassie);

        // Act
        for sql in [
            "BEGIN",
            "ALTER TABLE move_source.orders SET SCHEMA move_target",
            "COMMIT",
        ] {
            execute_statement(&cassie, &session, sql);
        }
        // Assert
        assert_moved_owned_sequences(
            &cassie,
            &session,
            [custom_sequence_id, identity_sequence_id, serial_sequence_id],
        );
        execute_statement(&cassie, &session, "INSERT INTO move_target.orders DEFAULT VALUES");

        // Restart to verify durable ownership and default rewrites.
        drop(session);
        drop(cassie);
        let restarted = Cassie::new_with_data_dir(&path).expect("reopen Cassie");
        restarted.startup().expect("restart");
        let session = restarted.create_session("tester", None);
        assert_moved_owned_sequences_after_restart(&restarted, &session);
        drop(session);
        drop(restarted);
        let _ = std::fs::remove_dir_all(path);
    });
}

fn assert_rollback_keeps_owned_sequences(cassie: &Cassie) {
    // Assert
    assert!(cassie.catalog.sequence_exists("move_source.order_ids"));
    assert!(!cassie.catalog.sequence_exists("move_target.order_ids"));
    for name in [
        "move_source.order_ids",
        "move_source.orders_serial_id_seq",
        "move_source.orders_generated_id_seq",
    ] {
        assert_eq!(
            cassie
                .catalog
                .get_sequence(name)
                .expect("owned sequence remains after rollback")
                .owned_by
                .as_ref()
                .map(|owner| owner.table.as_str()),
            Some("postgres.move_source.orders")
        );
    }
}

fn assert_moved_owned_sequences(cassie: &Cassie, session: &CassieSession, object_ids: [u64; 3]) {
    // Assert
    for name in [
        "move_source.order_ids",
        "move_source.orders_generated_id_seq",
        "move_source.orders_serial_id_seq",
    ] {
        assert!(!cassie.catalog.sequence_exists(name));
    }
    let moved_sequences = [
        cassie
            .catalog
            .get_sequence("move_target.order_ids")
            .expect("owned sequence moved to the table schema"),
        cassie
            .catalog
            .get_sequence("move_target.orders_generated_id_seq")
            .expect("identity sequence moved to the table schema"),
        cassie
            .catalog
            .get_sequence("move_target.orders_serial_id_seq")
            .expect("serial sequence moved to the table schema"),
    ];
    for (sequence, object_id) in moved_sequences.iter().zip(object_ids) {
        assert_eq!(sequence.object_id, object_id);
        assert_eq!(
            sequence.owned_by.as_ref().map(|owner| owner.table.as_str()),
            Some("postgres.move_target.orders")
        );
    }
    assert_eq!(
        query_rows(
            cassie,
            session,
            "SELECT id, generated_id, serial_id FROM move_target.orders ORDER BY id"
        ),
        vec![vec![Value::Int64(1), Value::Int64(1), Value::Int64(1)]]
    );
}

fn assert_moved_owned_sequences_after_restart(cassie: &Cassie, session: &CassieSession) {
    execute_statement(
        cassie,
        session,
        "INSERT INTO move_target.orders DEFAULT VALUES",
    );

    // Assert
    for name in [
        "move_target.order_ids",
        "move_target.orders_generated_id_seq",
        "move_target.orders_serial_id_seq",
    ] {
        assert!(cassie.catalog.sequence_exists(name));
    }
    for name in [
        "move_source.order_ids",
        "move_source.orders_generated_id_seq",
        "move_source.orders_serial_id_seq",
    ] {
        assert!(!cassie.catalog.sequence_exists(name));
    }
    assert_eq!(
        query_rows(
            cassie,
            session,
            "SELECT id, generated_id, serial_id FROM move_target.orders ORDER BY id"
        ),
        vec![
            vec![Value::Int64(1), Value::Int64(1), Value::Int64(1)],
            vec![Value::Int64(2), Value::Int64(2), Value::Int64(2)],
            vec![Value::Int64(3), Value::Int64(3), Value::Int64(3)]
        ]
    );
}

#[test]
fn should_reject_table_schema_move_when_owned_sequence_name_conflicts() {
    // Arrange
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("runtime");

    runtime.block_on(async {
        let cassie = crate::support_sql::new_in_memory_cassie().expect("create Cassie");
        cassie.startup().expect("startup");
        let session = cassie.create_session("tester", None);
        for sql in [
            "CREATE SCHEMA move_source",
            "CREATE SCHEMA move_target",
            "CREATE SEQUENCE move_source.order_ids",
            "CREATE TABLE move_source.orders (id BIGINT DEFAULT nextval('move_source.order_ids'::regclass))",
            "ALTER SEQUENCE move_source.order_ids OWNED BY move_source.orders.id",
            "CREATE TABLE move_target.other (id INT)",
            "CREATE INDEX order_ids ON move_target.other (id)",
        ] {
            execute_statement(&cassie, &session, sql);
        }

        // Act
        let error = cassie
            .execute_sql(
                &session,
                "ALTER TABLE move_source.orders SET SCHEMA move_target",
                vec![],
            )
            .expect_err("an index name conflict must reject the table and sequence move");

        // Assert
        assert!(error.to_string().contains("order_ids"));
        assert!(cassie.catalog.exists("move_source.orders"));
        assert!(!cassie.catalog.exists("move_target.orders"));
        assert!(cassie.catalog.sequence_exists("move_source.order_ids"));
        assert!(!cassie.catalog.sequence_exists("move_target.order_ids"));
        assert!(cassie
            .catalog
            .get_index("move_target.other", "order_ids")
            .is_some());
    });
}

