use super::*;

async fn table_and_sequence_count(client: &tokio_postgres::Client, name_prefix: &str) -> i64 {
    client
        .query_one(
            "SELECT count(*) FROM pg_catalog.pg_class \
             WHERE relname LIKE $1::text AND relkind IN ('r', 'S')",
            &[&name_prefix],
        )
        .await
        .expect("inspect table and sequence metadata")
        .get(0)
}

#[test]
fn should_restore_owned_sequence_when_truncate_restart_is_rolled_back() {
    // Arrange
    let runtime = current_thread_runtime();
    runtime.block_on(async {
        let server = CompatibilityServer::start("truncate_restart_identity_rollback").await;
        let (client, connection) = server.connect().await;
        client
            .batch_execute("CREATE SEQUENCE compat_truncate_identity_seq")
            .await
            .expect("create the restartable sequence");
        client
            .batch_execute(
                "CREATE TABLE compat_truncate_identity_rows (\
                   id BIGINT DEFAULT nextval('compat_truncate_identity_seq')\
                 )",
            )
            .await
            .expect("create a table with a sequence-backed default");
        client
            .batch_execute(
                "ALTER SEQUENCE compat_truncate_identity_seq \
                 OWNED BY compat_truncate_identity_rows.id",
            )
            .await
            .expect("make the sequence owned by its table column");
        let first: i64 = client
            .query_one(
                "INSERT INTO compat_truncate_identity_rows DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert the first sequence value")
            .try_get(0)
            .expect("sequence value");
        let second: i64 = client
            .query_one(
                "INSERT INTO compat_truncate_identity_rows DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert the second sequence value")
            .try_get(0)
            .expect("sequence value");
        client
            .batch_execute("BEGIN")
            .await
            .expect("begin the restart transaction");
        client
            .batch_execute("TRUNCATE TABLE compat_truncate_identity_rows RESTART IDENTITY")
            .await
            .expect("truncate and transactionally restart the owned sequence");
        let restarted: i64 = client
            .query_one(
                "INSERT INTO compat_truncate_identity_rows DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert after restarting the owned sequence")
            .try_get(0)
            .expect("sequence value");

        // Act
        client
            .batch_execute("ROLLBACK")
            .await
            .expect("roll back the table truncation and sequence restart");
        let after_rollback: i64 = client
            .query_one(
                "INSERT INTO compat_truncate_identity_rows DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert after rolling back the restart")
            .try_get(0)
            .expect("sequence value");

        // Assert
        assert_eq!((first, second, restarted, after_rollback), (1, 2, 1, 3));

        drop(client);
        server.shutdown(connection).await;
    });
}

#[test]
fn should_publish_implicit_identity_table_with_its_sequence_at_query_completion() {
    // Arrange
    let runtime = current_thread_runtime();
    runtime.block_on(async {
        let server = CompatibilityServer::start("implicit_identity_ddl_publication").await;
        let (owner, owner_connection) = server.connect().await;
        let (observer, observer_connection) = server.connect().await;
        owner
            .batch_execute(
                "CREATE TABLE compat_833_implicit_identity_rows \
                   (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)",
            )
            .await
            .expect("complete standalone identity-table DDL");

        // Act
        let owner_object_count =
            table_and_sequence_count(&owner, "compat_833_implicit_identity_rows%").await;
        let observer_object_count =
            table_and_sequence_count(&observer, "compat_833_implicit_identity_rows%").await;
        let inserted_id: i64 = observer
            .query_one(
                "INSERT INTO compat_833_implicit_identity_rows DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("use the identity sequence after the DDL Query completes")
            .try_get(0)
            .expect("identity value");
        let visible_id: i64 = owner
            .query_one("SELECT id FROM compat_833_implicit_identity_rows", &[])
            .await
            .expect("read the committed row from the owner session")
            .try_get(0)
            .expect("visible identity value");

        // Assert
        assert_eq!(owner_object_count, 2);
        assert_eq!(observer_object_count, 2);
        assert_eq!(inserted_id, 1);
        assert_eq!(visible_id, 1);

        drop((owner, observer));
        server.shutdown(owner_connection).await;
        observer_connection.abort();
        let _ = observer_connection.await;
    });
}

#[test]
fn should_publish_transaction_owned_generation_sequences_with_rows() {
    // Arrange
    let runtime = current_thread_runtime();
    runtime.block_on(async {
        let server = CompatibilityServer::start("transaction_owned_ddl_sequences").await;
        let (owner, owner_connection) = server.connect().await;
        let (observer, observer_connection) = server.connect().await;
        owner
            .batch_execute("BEGIN")
            .await
            .expect("begin the DDL transaction");
        owner
            .batch_execute(
                "CREATE TABLE compat_833_serial_rows \
                   (id SERIAL PRIMARY KEY, label TEXT)",
            )
            .await
            .expect("create the transaction-owned SERIAL sequence");
        owner
            .batch_execute(
                "CREATE TABLE compat_833_identity_rows \
                   (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label TEXT)",
            )
            .await
            .expect("create the transaction-owned IDENTITY sequence");

        // Act
        let direct_sequence_value: i64 = owner
            .query_one("SELECT nextval('compat_833_serial_rows_id_seq')", &[])
            .await
            .expect("advance the transaction-owned SERIAL sequence")
            .try_get(0)
            .expect("SERIAL nextval result");
        let serial_row_id: i32 = owner
            .query_one(
                "INSERT INTO compat_833_serial_rows (label) VALUES ('serial') RETURNING id",
                &[],
            )
            .await
            .expect("insert through the transaction-owned SERIAL default")
            .try_get(0)
            .expect("SERIAL default result");
        let identity_row_id: i64 = owner
            .query_one(
                "INSERT INTO compat_833_identity_rows (label) VALUES ('identity') RETURNING id",
                &[],
            )
            .await
            .expect("insert through the transaction-owned IDENTITY default")
            .try_get(0)
            .expect("IDENTITY default result");
        let owner_object_count = table_and_sequence_count(&owner, "compat_833_serial_rows%").await
            + table_and_sequence_count(&owner, "compat_833_identity_rows%").await;
        let observer_object_count = table_and_sequence_count(&observer, "compat_833_serial_rows%")
            .await
            + table_and_sequence_count(&observer, "compat_833_identity_rows%").await;
        owner
            .batch_execute("COMMIT")
            .await
            .expect("publish both tables, sequences, and rows");
        let committed_object_count = table_and_sequence_count(&observer, "compat_833_serial_rows%")
            .await
            + table_and_sequence_count(&observer, "compat_833_identity_rows%").await;
        let committed_serial_id: i32 = observer
            .query_one("SELECT id FROM compat_833_serial_rows", &[])
            .await
            .expect("read the committed SERIAL row")
            .try_get(0)
            .expect("committed SERIAL row id");
        let committed_identity_id: i64 = observer
            .query_one("SELECT id FROM compat_833_identity_rows", &[])
            .await
            .expect("read the committed IDENTITY row")
            .try_get(0)
            .expect("committed IDENTITY row id");

        // Assert
        assert_eq!(direct_sequence_value, 1);
        assert_eq!(serial_row_id, 2);
        assert_eq!(identity_row_id, 1);
        assert_eq!(owner_object_count, 4);
        assert_eq!(observer_object_count, 0);
        assert_eq!(committed_object_count, 4);
        assert_eq!(committed_serial_id, 2);
        assert_eq!(committed_identity_id, 1);

        drop((owner, observer));
        server.shutdown(owner_connection).await;
        observer_connection.abort();
        let _ = observer_connection.await;
    });
}

#[test]
fn should_restore_transaction_owned_identity_sequence_after_savepoint_rollback() {
    // Arrange
    let runtime = current_thread_runtime();
    runtime.block_on(async {
        let server = CompatibilityServer::start("transaction_owned_ddl_savepoint").await;
        let (owner, owner_connection) = server.connect().await;
        let (observer, observer_connection) = server.connect().await;
        owner
            .batch_execute("BEGIN")
            .await
            .expect("begin the DDL transaction");
        owner
            .batch_execute(
                "CREATE TABLE compat_833_savepoint_kept \
                   (id SERIAL PRIMARY KEY)",
            )
            .await
            .expect("create the table retained before the savepoint");
        let retained_id: i32 = owner
            .query_one(
                "INSERT INTO compat_833_savepoint_kept DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert into the table retained before the savepoint")
            .try_get(0)
            .expect("retained sequence value");
        owner
            .batch_execute("SAVEPOINT before_identity_ddl")
            .await
            .expect("create the catalog savepoint");
        owner
            .batch_execute(
                "CREATE TABLE compat_833_savepoint_removed \
                   (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)",
            )
            .await
            .expect("create the post-savepoint IDENTITY sequence");
        let removed_id: i64 = owner
            .query_one(
                "INSERT INTO compat_833_savepoint_removed DEFAULT VALUES RETURNING id",
                &[],
            )
            .await
            .expect("insert into the post-savepoint table")
            .try_get(0)
            .expect("post-savepoint sequence value");

        // Act
        owner
            .batch_execute("ROLLBACK TO SAVEPOINT before_identity_ddl")
            .await
            .expect("discard the post-savepoint table, sequence, and row");
        let owner_removed_count =
            table_and_sequence_count(&owner, "compat_833_savepoint_removed%").await;
        let observer_before_commit =
            table_and_sequence_count(&observer, "compat_833_savepoint_kept%").await
                + table_and_sequence_count(&observer, "compat_833_savepoint_removed%").await;
        owner
            .batch_execute("COMMIT")
            .await
            .expect("commit the state retained at the savepoint");
        let committed_kept_id: i32 = observer
            .query_one("SELECT id FROM compat_833_savepoint_kept", &[])
            .await
            .expect("read the retained row after commit")
            .try_get(0)
            .expect("committed retained sequence value");
        let committed_removed_count =
            table_and_sequence_count(&observer, "compat_833_savepoint_removed%").await;

        // Assert
        assert_eq!(retained_id, 1);
        assert_eq!(removed_id, 1);
        assert_eq!(owner_removed_count, 0);
        assert_eq!(observer_before_commit, 0);
        assert_eq!(committed_kept_id, 1);
        assert_eq!(committed_removed_count, 0);

        drop((owner, observer));
        server.shutdown(owner_connection).await;
        observer_connection.abort();
        let _ = observer_connection.await;
    });
}
